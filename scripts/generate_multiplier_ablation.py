def main():
    base = Path(__file__).resolve().parent.parent
    stream_dir = base / "config" / "streams" / "era5_1deg"
    config_dir = base / "config"

    print("Generating multiplier ablation configs...")
    print(f"  Stream dir: {stream_dir}")
    print(f"  Config dir: {config_dir}")
    print()

    for m in MULTIPLIERS:
        tag = mult_tag(m)

        # Compute level distribution for summary
        counts = {hl: 0 for hl in range(1, 6)}
        for v, l in AUTOCORR.items():
            counts[corr_to_hl(l, mult=m)] += 1
        dist = " | ".join(f"hl{hl}={counts[hl]}" for hl in range(1, 6))

        # Write stream config
        stream_path = stream_dir / f"era5_cm_mult{tag}.yml"
        stream_path.write_text(generate_stream_config(m))

        # Write training config
        config_path = config_dir / f"config_cm_mult{tag}.yml"
        config_path.write_text(generate_training_config(m))

        print(f"  mult={m:<4} -> {stream_path.name}, {config_path.name}  [{dist}]")

    print(f"\nGenerated {len(MULTIPLIERS)} config pairs.")
    print("\nTo train each ablation:")
    for m in MULTIPLIERS:
        tag = mult_tag(m)
        print(f"  uv run train --config config/config_cm_mult{tag}.yml")


if __name__ == "__main__":
    main()
