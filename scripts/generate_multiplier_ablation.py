def cell_size_km(h: int) -> float:
    n_cells = 12 * (4**h)
    return math.sqrt((4 * math.pi * EARTH_R**2) / n_cells)


def corr_to_hl(l_corr: float, mult: float, hl_min: int = 1, hl_max: int = 5) -> int:
    target = l_corr * mult
    for hl in range(hl_max, hl_min - 1, -1):
        if cell_size_km(hl) > target:
            return hl
    return hl_min


def mult_tag(m: float) -> str:
    """Convert multiplier to filename-safe tag, e.g. 0.25 -> '025', 1.5 -> '150'."""
    return f"{m * 100:.0f}".zfill(3)


